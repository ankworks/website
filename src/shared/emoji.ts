const SHORTCODE = /:([a-z0-9_+-]{1,32}):/gi;

/**
 * Replace known `:shortcode:` patterns with their emoji.
 *
 * Unknown shortcodes are left alone, and a lone `:` never starts a match that
 * spans other text.
 */
export function expandEmojiShortcodes(text: string): string {
  if (!text.includes(':')) return text;
  return text.replace(SHORTCODE, (match, name: string) => EMOJI_SHORTCODES[name.toLowerCase()] ?? match);
}
