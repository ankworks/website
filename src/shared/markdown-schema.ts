/**
 * Sanitization schema for rendered Markdown.
 *
 * The rendering pipeline is: remark (GFM) → rehype-raw (parsing raw HTML blocks
 * that GitHub-flavored Markdown allows) → rehype-sanitize with THIS schema.
 *
 * The schema extends hast-util-sanitize's GitHub-style defaults:
 * - `id` on h1–h6 only (GitHub-style heading anchors, no general DOM clobbering);
 * - `<style>` is stripped entirely (its CSS is never executed);
 * - `clobberPrefix` is empty so heading ids stay verbatim and TOC anchors match.
 *
 * Everything else behaves like GitHub's sanitizer: unknown tags are unwrapped
 * (children kept as text), scripts are dropped with their contents, event
 * handlers and unsafe URL schemes are removed. Component-level link and image
 * resolvers in `src/components/explorer/Markdown.tsx` add a second layer of
 * host/protocol checks after this pass.
 */
import { defaultSchema, type Options as SanitizeSchema } from 'rehype-sanitize';

const HEADING_TAGS = ['h1', 'h2', 'h3', 'h4', 'h5', 'h6'] as const;

type Attributes = NonNullable<SanitizeSchema['attributes']>;

const headingAttributes: Partial<Attributes> = {};
for (const tag of HEADING_TAGS) {
  headingAttributes[tag] = [...(defaultSchema.attributes?.[tag] ?? []), 'id'];
}

export const MARKDOWN_SANITIZE_SCHEMA: SanitizeSchema = {
  ...defaultSchema,
  // Heading ids are generated by `remarkHeadingIds` and must stay verbatim so
  // table-of-contents anchors match. `id`/`name` are only allowed on h1–h6.
  clobberPrefix: '',
  attributes: {
    ...defaultSchema.attributes,
    ...headingAttributes,
    img: [...(defaultSchema.attributes?.img ?? []), 'alt', 'width', 'height'],
    table: [...(defaultSchema.attributes?.table ?? []), 'width', 'align'],
    div: [...(defaultSchema.attributes?.div ?? []), 'align'],
  },
  // `<style>` content is CSS, not content; drop it instead of leaking it as
  // text (script is already in the default strip list).
  strip: [...(defaultSchema.strip ?? []), 'style'],
};
